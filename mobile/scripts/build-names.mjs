// Country, language and currency names in each of the app's languages.
// The website gets these from Intl.DisplayNames at runtime; Hermes on phones doesn't
// carry that data, so the app ships them as a table. Rerun after adding a language,
// in a normal terminal: cd ~/stugora/mobile && npm run build:names
import { readFileSync, writeFileSync } from "node:fs";

const locales = readFileSync(new URL("../../frontend/src/i18n/locales.ts", import.meta.url), "utf8");
const intl = Object.fromEntries([...locales.matchAll(/^\s+(\w\w): \{ native: "[^"]+", intl: "([^"]+)"/gm)].map((m) => [m[1], m[2]]));
const langs = Object.keys(intl);
const countries = ["FI", "SE", "NO", "DK", "IS", "EE", "LV", "LT"];
const currencies = ["EUR", "SEK", "NOK", "DKK", "ISK"];
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const table = {};
for (const lang of langs) {
  const of = (type, code) => new Intl.DisplayNames([intl[lang]], { type }).of(code) ?? code;
  table[lang] = {
    country: Object.fromEntries(countries.map((c) => [c, of("region", c)])),
    language: Object.fromEntries(langs.map((l) => [l, of("language", l)])),
    currency: Object.fromEntries(currencies.map((c) => [c, cap(of("currency", c))])),
  };
}
const out = `// Generated by scripts/build-names.mjs from Node's CLDR data. Do not edit by hand.
export const NAMES = ${JSON.stringify(table, null, 2)} as const;
`;
writeFileSync(new URL("../src/text/names.ts", import.meta.url), out);
console.log(`names for ${langs.length} languages`);
